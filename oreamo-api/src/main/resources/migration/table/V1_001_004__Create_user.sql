CREATE TABLE TB_USER
(
    USERNAME                    VARCHAR(50)  NOT NULL UNIQUE,
    NAME                        VARCHAR(100) NOT NULL,
    EMAIL                       VARCHAR(100) NOT NULL,
    PASSWORD                    VARCHAR(255) NOT NULL,
    ROLE_CODE                   VARCHAR(50)  NOT NULL,
    PROFILE_IMAGE_FILE_GROUP_ID VARCHAR(36)  NULL,
    DATA_STATUS                 VARCHAR(10)  NOT NULL DEFAULT 'ENABLED',
    CREATED_BY                  VARCHAR(50)  NOT NULL DEFAULT 'oreamo-system',
    CREATED_AT                  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY                  VARCHAR(50)  NOT NULL DEFAULT 'oreamo-system',
    UPDATED_AT                  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT TB_USER_PK PRIMARY KEY (USERNAME),
    CONSTRAINT TB_USER_ROLE_CODE_FK FOREIGN KEY (ROLE_CODE) REFERENCES TB_ROLE (ROLE_CODE)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
)
